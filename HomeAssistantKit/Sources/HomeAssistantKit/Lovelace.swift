import Foundation

/// A Lovelace dashboard as listed in the sidebar (`get_panels`).
public struct HADashboard: Hashable, Identifiable, Sendable {
    /// nil for the default dashboard.
    public let urlPath: String?
    public let title: String
    public let icon: String?

    public var id: String { urlPath ?? "lovelace" }

    public init(urlPath: String?, title: String, icon: String? = nil) {
        self.urlPath = urlPath
        self.title = title
        self.icon = icon
    }

    /// Extracts Lovelace dashboards from a `get_panels` result.
    public static func fromPanels(_ panels: JSONValue) -> [HADashboard] {
        (panels.objectValue ?? [:]).values
            .filter { $0["component_name"]?.stringValue == "lovelace" }
            .compactMap { panel -> HADashboard? in
                guard let path = panel["url_path"]?.stringValue else { return nil }
                let isDefault = path == "lovelace"
                return HADashboard(
                    urlPath: isDefault ? nil : path,
                    title: panel["title"]?.stringValue ?? "Overview",
                    icon: panel["icon"]?.stringValue
                )
            }
            .sorted { lhs, rhs in
                // Default dashboard first, then alphabetical, as in the HA sidebar.
                if (lhs.urlPath == nil) != (rhs.urlPath == nil) { return lhs.urlPath == nil }
                return lhs.title.localizedCaseInsensitiveCompare(rhs.title) == .orderedAscending
            }
    }
}

/// A parsed dashboard configuration (`lovelace/config`).
public struct LovelaceConfig: Sendable {
    public let title: String?
    public let views: [LovelaceView]
    /// Dashboards generated by a strategy (e.g. the map) have no stored cards.
    public let isStrategy: Bool

    public init(_ json: JSONValue) {
        title = json["title"]?.stringValue
        isStrategy = json["strategy"] != nil
        views = (json["views"]?.arrayValue ?? []).enumerated().map { index, view in
            LovelaceView(view, index: index)
        }
    }
}

public struct LovelaceView: Identifiable, Sendable {
    public enum Layout: String, Sendable {
        case masonry, panel, sidebar, sections
    }

    public let id: String
    public let title: String
    public let icon: String?
    public let layout: Layout
    public let cards: [LovelaceCard]
    public let sections: [LovelaceSection]

    init(_ json: JSONValue, index: Int) {
        let id = json["path"]?.stringValue ?? "view-\(index)"
        self.id = id
        title = json["title"]?.stringValue ?? "View \(index + 1)"
        icon = json["icon"]?.stringValue
        layout = json["type"]?.stringValue.flatMap(Layout.init(rawValue:)) ?? .masonry
        cards = LovelaceCard.list(json["cards"], idPrefix: "\(id)/c")
        sections = (json["sections"]?.arrayValue ?? []).enumerated().map { sectionIndex, section in
            LovelaceSection(section, id: "\(id)/s\(sectionIndex)")
        }
    }

    /// Every card in the view, whichever layout it uses.
    public var allCards: [LovelaceCard] {
        cards + sections.flatMap(\.cards)
    }
}

public struct LovelaceSection: Identifiable, Sendable {
    public let id: String
    public let columnSpan: Int
    public let cards: [LovelaceCard]

    init(_ json: JSONValue, id: String) {
        self.id = id
        columnSpan = json["column_span"]?.intValue ?? 1
        cards = LovelaceCard.list(json["cards"], idPrefix: "\(id)/c")
    }
}

/// One card. The raw config is kept because each card type reads different keys.
public struct LovelaceCard: Identifiable, Sendable {
    public let id: String
    public let type: String
    public let config: JSONValue
    /// Child cards of stacks and grids.
    public let cards: [LovelaceCard]

    public init(_ config: JSONValue, id: String) {
        self.id = id
        self.config = config
        type = config["type"]?.stringValue ?? "unknown"
        cards = LovelaceCard.list(config["cards"], idPrefix: "\(id)/")
    }

    static func list(_ json: JSONValue?, idPrefix: String) -> [LovelaceCard] {
        (json?.arrayValue ?? []).enumerated().map { index, card in
            LovelaceCard(card, id: "\(idPrefix)\(index)")
        }
    }

    public func string(_ key: String) -> String? { config[key]?.stringValue }
    public func double(_ key: String) -> Double? { config[key]?.doubleValue }
    public func strings(_ key: String) -> [String] {
        if let single = config[key]?.stringValue { return [single] }
        return config[key]?.arrayValue?.compactMap(\.stringValue) ?? []
    }

    public var title: String? { string("title") }
    public var entity: String? { string("entity") }

    /// The `entities` list, which may mix plain IDs and `{entity: ...}` objects.
    public var entities: [LovelaceEntityRef] {
        (config["entities"]?.arrayValue ?? []).compactMap(LovelaceEntityRef.init)
    }
}

public struct LovelaceEntityRef: Hashable, Sendable {
    public let entityId: String
    public let name: String?

    public init(entityId: String, name: String? = nil) {
        self.entityId = entityId
        self.name = name
    }

    init?(_ json: JSONValue) {
        if let id = json.stringValue {
            self.init(entityId: id)
        } else if let id = json["entity"]?.stringValue {
            self.init(entityId: id, name: json["name"]?.stringValue)
        } else {
            return nil
        }
    }
}
